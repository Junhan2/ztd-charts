/** 키 순서는 ChartDef 그대로예요 (CLI, MCP, 스키마 파일이 이 순서로 써요) */
function fill({ type, level, group, summary, useWhen, avoidWhen, why, options, example, ...extra }: ChartEntry, i: number): ChartDef {
  const { name, component } = META[type];
  const { card, ...spec } = example;
  const { legend, ...text } = card;
  return {
    type,
    component,
    name,
    nameEn: name,
    level,
    group,
    summary,
    useWhen,
    avoidWhen,
    why,
    encoding: CHANNELS[type],
    options,
    example: { type, ...spec, card: { number: String(i + 1).padStart(2, "0"), title: name, ...text, level, ...(legend && { legend }) } },
    ...extra,
  };
}

/** 차트 44종. 글과 예시는 영어, 한글은 localizeDef(def, "ko") 또는 chartsIn("ko") */
export const CHARTS: ChartDef[] = /* @__PURE__ */ ENTRIES.map(fill);

export const CHART_TYPES = /* @__PURE__ */ CHARTS.map((c) => c.type);

export function getChartDef(type: string): ChartDef | undefined {
  return CHARTS.find((c) => c.type === type || c.type.toLowerCase() === type.toLowerCase() || c.component.toLowerCase() === type.toLowerCase());
}

